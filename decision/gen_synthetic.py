def _scenario_tool(rng, lang):
    words = TOOL_TEXT[lang]
    offered = rng.sample(sorted(TOOLS), 3)
    shape = rng.choice(("complete", "complete", "missing", "unsupported"))
    tool = rng.choice(offered)
    params = {name: rng.choice(VALUES[name]) for name in TOOLS[tool]}
    if shape == "unsupported":
        request, given, answer, why = UNSUPPORTED[lang], {}, "none", "no offered tool fits"
    else:
        request = TOOL_TASKS[tool][lang].format(**params)
        given = dict(params)
        answer, why = f"call_{tool}", "every required parameter is given"
        if shape == "missing":
            dropped = rng.choice(TOOLS[tool])
            del given[dropped]
            request = request.replace(params[dropped], "…")
            answer, why = "ask", f"required parameter {dropped} is missing"
    options = [
        {"id": f"call_{name}", "text": words["tool"].format(name=name, params=", ".join(TOOLS[name]))}
        for name in offered
    ]
    options += [{"id": "ask", "text": words["ask"]}, {"id": "none", "text": words["none"]}]
    known = (
        words["known"].format(params=", ".join(f"{k}={v}" for k, v in sorted(given.items())))
        if given
        else words["nothing"]
    )
    return {
        "family": "next_tool",
        "kind": "choice",
        "question": words["q"],
        "options": options,
        "insufficient": None,
        "objective": words["obj"],
        "evidence": [("claim", request), ("confirmed", known)],
        "facts": {"tools_offered": len(offered)},
        "answer": answer,
        "why": why,
    }


GENERATORS = {
    "budget-gate": _scenario_budget,
    "ready-receipt": _scenario_ready,
    "deadline": _scenario_deadline,
    "entailment": _scenario_entail,
    "tool-select": _scenario_tool,
    "claim-review": _scenario_review,
    "topic-route": _scenario_topic,
    "severity-score": _scenario_severity,
}


def _record(generator, seed, index, variant, lang, scenario, options, parent):
    group = f"syn-{generator}-{seed}-{index}"
    return {
        "id": f"{group}-{variant}",
        "group": group,
        "family": scenario["family"],
        "kind": scenario["kind"],
        "lang": lang,
        "question": scenario["question"],
        "options": [dict(option) for option in options],
        "insufficient_option": scenario["insufficient"],
        "context": {
            "objective": scenario["objective"],
            "evidence": [
                {"ref": f"e{number}", "source": source, "text": text}
                for number, (source, text) in enumerate(scenario["evidence"], 1)
            ],
            "pending": list(scenario.get("pending", [])),
            "facts": dict(scenario["facts"]),
        },
        "answer": scenario["answer"],
        "rationale": scenario["why"],
        "generator": generator,
        "parent": parent,
        "split": assign_split(group),
        "licence": LICENCE,
        "attribution": ATTRIBUTION,
        "meta": {"generator_version": GENERATOR_VERSION, "seed": seed, "index": index, "variant": variant},
    }


def generate(seed: int, count: int, languages=LANGUAGES):
    """Yield the records of ``count`` scenarios, children right after their parent.

    Scenario ``index`` uses generator ``sorted(GENERATORS)[index % 8]`` and
    language ``languages[(index // 8) % len(languages)]``. A scenario whose
    content repeats an earlier one is redrawn up to 32 times and then dropped,
    so identical content is never emitted under two groups (small scenario
    spaces such as budget-gate saturate and yield fewer records).
    """
    languages = tuple(languages)
    if not languages or set(languages) - set(LANGUAGES):
        raise ValueError("unsupported language")
    rng = random.Random(f"{GENERATOR_VERSION}:{seed}")
    names = sorted(GENERATORS)
    seen = set()
    for index in range(count):
        generator = names[index % len(names)]
        lang = languages[(index // len(names)) % len(languages)]
        for _ in range(32):
            scenario = GENERATORS[generator](rng, lang)
            # Order- and id-blind key, so a permuted child never equals another scenario.
            key = canonical(
                [scenario["question"], scenario["facts"], lang]
                + [sorted(canonical([o["text"], o.get("level")]).decode() for o in scenario["options"])]
                + [[list(item) for item in scenario["evidence"]], scenario.get("pending", [])]
            )
            if key not in seen:
                seen.add(key)
                break
        else:
            continue
        options = scenario["options"]
        base = _record(generator, seed, index, "a", lang, scenario, options, None)
        yield base
        if scenario["kind"] != "choice":
            continue  # yes/no and ordinal options keep their fixed order
        permuted = list(options)
        while len(permuted) > 1 and permuted == options:
            rng.shuffle(permuted)
        yield _record(generator, seed, index, "b", lang, scenario, permuted, base["id"])


def write(seed: int, count: int, out, languages=LANGUAGES) -> dict:
    """Generate, check and write the JSONL file; return the Checker summary."""
    with open(out, "wb") as sink:
        checker = Checker(sink)
        for record in generate(seed, count, languages):
            checker.add(record)
    return checker.summary()


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--seed", type=int, required=True)
    parser.add_argument("--count", type=int, required=True, help="number of scenarios")
    parser.add_argument("--languages", default=",".join(LANGUAGES))
    parser.add_argument("--out", required=True, type=Path)
    args = parser.parse_args(argv)
    languages = tuple(part for part in args.languages.split(",") if part)
    summary = write(args.seed, args.count, args.out, languages)
    print(canonical(summary).decode())
    return 0



def _scenario_entail(rng, lang):
    words = ENTAIL[lang]
    entity = rng.choice(ENTITIES[lang])
    stated = {name: rng.randrange(3) for name in PROPERTIES if rng.random() < 0.7}
    asked = rng.choice(sorted(PROPERTIES))
    if asked in stated:
        same = rng.random() < 0.5
        value = stated[asked] if same else (stated[asked] + rng.randint(1, 2)) % 3
        answer = "yes" if same else "no"
        why = "stated with the same value" if same else "stated with another value"
    else:
        value, answer, why = rng.randrange(3), "unknown", "the property is not stated"

    def sentence(name, index):
        return words[name].format(entity=entity, value=PROPERTIES[name][lang][index])

    return {
        "family": "entail",
        "kind": "yes_no",
        "question": words["q"].format(hypothesis=sentence(asked, value)),
        "options": [{"id": key, "text": words[key]} for key in ("yes", "no", "unknown")],
        "insufficient": "unknown",
        "objective": words["obj"],
        "evidence": [("confirmed", sentence(name, index) + ".") for name, index in sorted(stated.items())],
        "facts": {},
        "answer": answer,
        "why": why,
    }



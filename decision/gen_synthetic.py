def _scenario_review(rng, lang):
    fact, opposite = FACTS[lang]
    component = rng.choice(COMPONENTS)
    fact, opposite = f"{component}: {fact}", f"{component}: {opposite}"
    shape = rng.choice(("claim", "confirmed", "conflict"))
    t = TEXT[lang]
    evidence = [("claim", t["claim"].format(fact=fact))]
    answer, why = "semantic_review", "only an agent claim supports it"
    if shape == "confirmed":
        evidence.append(("receipt", t["confirmed"].format(fact=fact)))
        answer, why = "continue", "a receipt confirms the claim"
    elif shape == "conflict":
        evidence.append(("receipt", t["contradiction"].format(opposite=opposite)))
        answer, why = "clarify", "the receipt contradicts the claim"
    return {
        "family": "review_need",
        "kind": "choice",
        "question": t["review_q"],
        "options": _options(lang, ("continue", "semantic_review", "clarify")),
        "insufficient": None,
        "objective": t["review_obj"],
        "evidence": evidence,
        "facts": {},
        "answer": answer,
        "why": why,
    }


def _scenario_topic(rng, lang):
    topic = rng.choice(sorted(TOPICS))
    labels, messages = TOPICS[topic]
    absent = rng.random() < 0.25  # about a quarter: the right topic is not offered
    choices = [key for key in sorted(TOPICS) if not (absent and key == topic)]
    t = TEXT[lang]
    options = [{"id": key, "text": TOPICS[key][0][lang]} for key in choices]
    options.append({"id": "none", "text": t["none"]})
    return {
        "family": "classify",
        "kind": "choice",
        "question": t["topic_q"],
        "options": options,
        "insufficient": None,
        "objective": t["topic_obj"],
        "evidence": [("claim", f"[#{rng.randint(1000, 9999)}] {rng.choice(messages[lang])}")],
        "facts": {},
        "answer": "none" if absent else topic,
        "why": "the correct topic is not offered" if absent else f"message is about {topic}",
    }


def _scenario_severity(rng, lang):
    failing = rng.sample(CHECKS, rng.randint(0, 3))
    t = TEXT[lang]
    evidence = [
        ("receipt", t["check_fail" if name in failing else "check_pass"].format(name=name))
        for name in CHECKS
    ]
    return {
        "family": "grade",
        "kind": "score",
        "question": t["severity_q"],
        "options": [
            {"id": f"level{level}", "text": t["level"].format(level=level), "level": level}
            for level in range(4)
        ],
        "insufficient": None,
        "objective": t["severity_obj"],
        "evidence": evidence,
        "facts": {"checks": len(CHECKS)},
        "answer": f"level{len(failing)}",
        "why": f"{len(failing)} checks failed",
    }


